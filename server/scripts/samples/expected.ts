import { completionDate, type GeneratedPdf } from './contractMainWorks';
import { SUMMARY_SHEET, type BillLayout, type BoqLayout } from './lib/boqLayout';
import { addDays, day, isoDate, longDate, ordinal } from './lib/dates';
import { dueDate, dueText } from './lib/due';
import { formatAmount, lineAmount, sumAmounts } from './lib/money';
import { diffRevisions } from './lib/revisionDiff';
import { contract, parties, project, SAMPLE_FOLDER } from './project';

export interface ExpectedInput {
  contract: GeneratedPdf;
  boqRev0: BoqLayout;
  boqRev1: BoqLayout;
}

interface PdfSource {
  kind: 'pdf';
  document: string;
  page: number;
  quote: string | null;
}

interface ExcelSource {
  kind: 'excel';
  document: string;
  sheet: string;
  rowFrom: number;
  rowTo: number;
}

const THRESHOLD = 1_000_000;

/**
 * Ground truth for the sample folder, assembled from the same data the documents were written from.
 * One top-level key per topic so later sample sets can add their own.
 */
export function buildExpected(input: ExpectedInput) {
  const boqs = [input.boqRev0, input.boqRev1];
  return {
    about:
      'Ground truth for the Atlas sample folder. Generated by "pnpm samples" from server/scripts/samples; do not edit by hand. Sources use the same shape as @atlas/shared Source; Excel rows are 1-based as Excel shows them.',
    folder: SAMPLE_FOLDER,
    project: {
      name: project.name,
      location: project.location,
      description: project.description,
      employer: parties.employer.name,
      contractor: parties.contractor.name,
      engineer: parties.engineer.name,
    },
    filesStatus: {
      [input.contract.fileName]: { kind: 'pdf', status: 'ok', pages: input.contract.pageCount },
      ...Object.fromEntries(
        boqs.map((layout) => [
          layout.revision.fileName,
          { kind: 'excel', status: 'ok', sheets: [SUMMARY_SHEET, ...layout.bills.map((bill) => bill.bill.sheet)] },
        ]),
      ),
    },
    facts: contractFacts(input.contract),
    schedule: contractSchedule(input.contract),
    boqTotals: Object.fromEntries(boqs.map((layout) => [layout.revision.fileName, boqTotals(layout)])),
    rowsAboveSar1m: boqs.flatMap(rowsAbove),
    arithmeticErrors: boqs.flatMap(arithmeticErrors),
    wrongSubtotals: boqs.flatMap(wrongSubtotals),
    revisionDiff: diffRevisions(input.boqRev0, input.boqRev1),
  };
}

export type Expected = ReturnType<typeof buildExpected>;

function pdfSource(pdf: GeneratedPdf, key: string, quote: string | null = null): PdfSource {
  const page = pdf.pages[key];
  if (page === undefined) throw new Error(`The contract has no mark ${key}`);
  return { kind: 'pdf', document: pdf.fileName, page, quote };
}

function percentOfPrice(percent: number): number {
  return lineAmount(contract.price.amount, percent / 100);
}

function contractFacts(pdf: GeneratedPdf) {
  const price = contract.price;
  const priceText = `SAR ${formatAmount(price.amount)}`;
  const { retention, liquidatedDamages, advancePayment, payment } = contract;
  return {
    contractNumber: contract.number,
    contractValue: {
      amount: price.amount,
      currency: price.currency,
      text: priceText,
      shortText: price.shortText,
      excludesVat: true,
      vatPercent: contract.vatPercent,
      source: pdfSource(pdf, 'contractPrice', priceText),
      shortTextSource: pdfSource(pdf, 'contractPriceShort', price.shortText),
    },
    parties: (['employer', 'contractor', 'engineer'] as const).map((key) => ({
      role: parties[key].role,
      name: parties[key].name,
      representative: parties[key].representative,
      source: pdfSource(pdf, key, parties[key].name),
    })),
    scopeOfWork: {
      source: pdfSource(pdf, 'scopeOfWork', 'Scope of Work'),
      items: contract.scope.map((text, i) => ({ text, page: pdfSource(pdf, `scope.${i + 1}`).page })),
      exclusions: contract.exclusions.map((text, i) => ({ text, page: pdfSource(pdf, `exclusion.${i + 1}`).page })),
    },
    paymentTerms: {
      source: pdfSource(pdf, 'paymentTerms', 'Payment Terms'),
      advancePayment: {
        percentOfPrice: advancePayment.percent,
        amountDerived: percentOfPrice(advancePayment.percent),
        paidWithinDays: advancePayment.paidWithinDays,
        recoveryPercentOfEachCertificate: advancePayment.recoveryPercent,
        source: pdfSource(pdf, 'advancePayment'),
      },
      statementDue: { text: `by the ${ordinal(payment.statementDay)} day of each month`, source: pdfSource(pdf, 'paymentStatement') },
      certificateWithinDays: { days: payment.certifyWithinDays, source: pdfSource(pdf, 'paymentCertificate') },
      paymentWithinDays: { days: payment.payWithinDays, source: pdfSource(pdf, 'paymentPeriod') },
      finalPaymentWithinDays: { days: payment.finalPayWithinDays, source: pdfSource(pdf, 'finalPayment') },
    },
    retention: {
      percentOfEachPayment: retention.percentOfEachPayment,
      limitPercentOfPrice: retention.limitPercentOfPrice,
      limitAmountDerived: percentOfPrice(retention.limitPercentOfPrice),
      releasedAtTakingOverPercent: retention.releasedAtTakingOverPercent,
      releasedAfterDefectsPeriodPercent: 100 - retention.releasedAtTakingOverPercent,
      source: pdfSource(pdf, 'retention'),
      releaseSource: pdfSource(pdf, 'retentionRelease'),
    },
    liquidatedDamages: {
      perDay: liquidatedDamages.perDay,
      currency: price.currency,
      text: `SAR ${formatAmount(liquidatedDamages.perDay)} per day of delay`,
      limitPercentOfPrice: liquidatedDamages.limitPercentOfPrice,
      limitAmountDerived: percentOfPrice(liquidatedDamages.limitPercentOfPrice),
      source: pdfSource(pdf, 'liquidatedDamages'),
    },
    performanceSecurity: {
      percentOfPrice: contract.performanceSecurityPercent,
      amountDerived: percentOfPrice(contract.performanceSecurityPercent),
      source: pdfSource(pdf, 'performanceSecurity'),
    },
    notes: [
      'Fields ending in "Derived" are not written in the contract; they are percentages of the Contract Price computed by code.',
      'The Phase 1 BOQ covers only part of the Works (Article 2.4), so its total is lower than the Contract Price.',
    ],
  };
}

function contractSchedule(pdf: GeneratedPdf) {
  const commencement = contract.commencement.date;
  return {
    contractDate: {
      date: contract.contractDate.date,
      text: longDate(day(contract.contractDate.date)),
      hijri: contract.contractDate.hijri,
      source: pdfSource(pdf, 'contractDate'),
    },
    letterOfAcceptance: {
      date: contract.letterOfAcceptance,
      text: longDate(day(contract.letterOfAcceptance)),
      source: pdfSource(pdf, 'letterOfAcceptance'),
    },
    commencementDate: {
      date: commencement,
      text: longDate(day(commencement)),
      hijri: contract.commencement.hijri,
      source: pdfSource(pdf, 'commencementDate'),
      hijriSource: pdfSource(pdf, 'commencementHijri', contract.commencement.hijri),
    },
    timeForCompletion: {
      months: contract.timeForCompletionMonths,
      text: `Time for Completion: ${contract.timeForCompletionMonths} months`,
      completionDate: isoDate(completionDate()),
      completionText: longDate(completionDate()),
      source: pdfSource(pdf, 'timeForCompletion'),
    },
    durations: [
      {
        label: 'Baseline Programme',
        text: 'within 28 days of the Commencement Date',
        days: 28,
        date: dueDate({ kind: 'afterCommencement', days: 28 }, commencement),
        source: pdfSource(pdf, 'baselineProgramme'),
      },
      {
        label: "Engineer's review of each design submission",
        text: `within ${contract.designReviewDays} days of receiving it`,
        days: contract.designReviewDays,
        date: null,
        source: pdfSource(pdf, 'designReview'),
      },
      {
        label: 'Defects Notification Period',
        text: `${contract.defectsNotificationMonths} months from the date in the Taking-Over Certificate`,
        months: contract.defectsNotificationMonths,
        date: null,
        source: pdfSource(pdf, 'defectsNotificationPeriod'),
      },
      {
        label: 'Performance Security',
        text: 'within 28 days of receiving the Letter of Acceptance',
        days: 28,
        date: isoDate(addDays(day(contract.letterOfAcceptance), 28)),
        source: pdfSource(pdf, 'performanceSecurity'),
      },
    ],
    milestones: contract.milestones.map((m) => ({
      id: m.id,
      title: m.title,
      dueText: dueText(m.due),
      date: dueDate(m.due, commencement),
      source: pdfSource(pdf, `milestone.${m.id}`),
    })),
    deliverables: contract.deliverables.map((d) => ({
      id: d.id,
      name: d.name,
      dueText: dueText(d.due),
      date: dueDate(d.due, commencement),
      source: pdfSource(pdf, `deliverable.${d.id}`),
    })),
  };
}

function excelSource(layout: BoqLayout, sheet: string, rowFrom: number, rowTo = rowFrom): ExcelSource {
  return { kind: 'excel', document: layout.revision.fileName, sheet, rowFrom, rowTo };
}

function boqTotals(layout: BoqLayout) {
  const currency = layout.revision.currency;
  const items = layout.bills.flatMap((bill) => bill.items);
  const summary = layout.summary;
  return {
    basis: 'Sum of the Amount column over item rows only (section, sub-total and total rows excluded), amounts as written in the file.',
    itemRows: items.length,
    totals: [{ currency, amount: sumAmounts(items.map((line) => line.amount)) }],
    totalsIfEveryAmountWereQtyTimesRate: [{ currency, amount: sumAmounts(items.map((line) => line.correctAmount)) }],
    statedGrandTotal: { currency, amount: summary.total, source: excelSource(layout, SUMMARY_SHEET, summary.totalRow) },
    bills: layout.bills.map((bill) => ({
      sheet: bill.bill.sheet,
      title: bill.bill.title,
      itemRows: bill.items.length,
      total: sumAmounts(bill.items.map((line) => line.amount)),
      statedTotal: bill.total.value,
      statedTotalSource: excelSource(layout, bill.bill.sheet, bill.total.row),
      source: excelSource(layout, bill.bill.sheet, bill.items[0]?.row ?? bill.total.row, bill.total.row),
    })),
  };
}

function placed(layout: BoqLayout) {
  return layout.bills.flatMap((bill: BillLayout) => bill.items.map((line) => ({ bill, line })));
}

function rowsAbove(layout: BoqLayout) {
  return placed(layout)
    .filter(({ line }) => line.amount > THRESHOLD)
    .map(({ bill, line }) => ({
      file: layout.revision.fileName,
      sheet: bill.bill.sheet,
      row: line.row,
      item: line.item.code,
      description: line.item.description,
      amount: line.amount,
      currency: layout.revision.currency,
    }));
}

function arithmeticErrors(layout: BoqLayout) {
  return placed(layout)
    .filter(({ line }) => line.amount !== line.correctAmount)
    .map(({ bill, line }) => ({
      file: layout.revision.fileName,
      sheet: bill.bill.sheet,
      row: line.row,
      item: line.item.code,
      description: line.item.description,
      quantity: line.item.quantity,
      rate: line.item.rate,
      statedAmount: line.amount,
      correctAmount: line.correctAmount,
      difference: sumAmounts([line.amount, -line.correctAmount]),
      currency: layout.revision.currency,
    }));
}

function wrongSubtotals(layout: BoqLayout) {
  return layout.bills.flatMap((bill) =>
    bill.subtotals
      .filter((line) => line.value !== line.correctValue)
      .map((line) => {
        const missed = bill.items.filter((item) => item.section === line.section && item.row > line.rangeTo);
        return {
          file: layout.revision.fileName,
          sheet: bill.bill.sheet,
          row: line.row,
          label: line.text,
          formula: `=${line.formula}`,
          statedValue: line.value,
          correctValue: line.correctValue,
          difference: sumAmounts([line.value, -line.correctValue]),
          missedItems: missed.map((item) => ({ item: item.item.code, row: item.row, amount: item.amount })),
          currency: layout.revision.currency,
        };
      }),
  );
}
